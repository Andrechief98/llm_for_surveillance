def get_inspection_value(value):

    if not isinstance(value, str) or value.strip() == "":
        return 0.0

    value = value.lower().strip()

    if value.startswith("robot"):
        return 1.0

    if value.startswith("camera"):
        return 0.5

    print(f"WARNING: Unknown inspection value: {value}")

    return 0.0


def process_hitl_custom_run(run_data, world_areas):

    original_matrix = run_data.get("matrix", {})

    all_areas = world_areas

    # Separate matrices
    matrix_llm = {}
    matrix_human = {}

    for turn, turn_data in original_matrix.items():

        if not isinstance(turn_data, dict):
            continue

        llm_inspections = turn_data.get("LLM", {})
        human_inspections = turn_data.get("human", {})

        matrix_llm[int(turn)] = {}
        matrix_human[int(turn)] = {}

        for area in all_areas:

            # -----------------------------
            # LLM
            # -----------------------------

            llm_value = llm_inspections.get(area, "")

            matrix_llm[int(turn)][area] = (
                get_inspection_value(llm_value)
            )

            # -----------------------------
            # HUMAN
            # -----------------------------

            human_value = human_inspections.get(area, "")

            matrix_human[int(turn)][area] = (
                get_inspection_value(human_value)
            )

    # Convert to DataFrames
    df_llm = pd.DataFrame.from_dict(
        matrix_llm,
        orient="index"
    ).reindex(columns=all_areas, fill_value=0.0)

    df_human = pd.DataFrame.from_dict(
        matrix_human,
        orient="index"
    ).reindex(columns=all_areas, fill_value=0.0)

    df_llm.index.name = "LLM_turn"
    df_human.index.name = "LLM_turn"

    return df_llm, df_human


def normalized_hamming_distance_by_turn(
    matrix_llm,
    matrix_human
):
    """
    Computes normalized Hamming distance for each turn.

    Input:
    - matrix_llm (pandas DataFrame)
    - matrix_human (pandas DataFrame)

    Matching:
        LLM turn 1 <-> Human turn 1
        LLM turn 2 <-> Human turn 2
        ...

    Normalization:
        Hamming distance / number of areas considered
        by either LLM or Human (union of active areas).

    Missing turns are treated as zero vectors.
    If both vectors contain only zeros, distance = 0.
    """

    all_turns = sorted(
        set(matrix_llm.index) | set(matrix_human.index)
    )

    distances = {}

    for turn in all_turns:

        # Extract corresponding turn vectors
        if turn in matrix_llm.index:
            llm_vector = matrix_llm.loc[turn].to_numpy(dtype=float)
        else:
            llm_vector = np.zeros(len(matrix_llm.columns))

        if turn in matrix_human.index:
            human_vector = matrix_human.loc[turn].to_numpy(dtype=float)
        else:
            human_vector = np.zeros(len(matrix_human.columns))

        # Hamming distance: number of differing areas
        hamming = np.sum(llm_vector != human_vector)

        # Union of areas considered by LLM or Human
        active_union = np.count_nonzero(
            (llm_vector != 0) | (human_vector != 0)
        )

        # Normalization
        if active_union == 0:
            normalized_distance = 0.0
        else:
            normalized_distance = hamming / active_union

        distances[int(turn)] = float(normalized_distance)

    # Mean across turns
    mean_distance = (
        float(np.mean(list(distances.values())))
        if distances else 0.0
    )

    return distances, mean_distance


def dataframe_to_dict(matrix):

    return {
        str(index): {
            str(column): float(matrix.loc[index, column])
            for column in matrix.columns
        }
        for index in matrix.index
    }


def find_stored_runs(data, path=()):

    if isinstance(data, dict):

        if (
            "sensor_sequence" in data
            and "success" in data
        ):
            yield path, data
            return

        if (
            "sensor_sequence" in data
            and "matrix" in data
        ):
            yield path, data
            return

        for key, value in data.items():
            yield from find_stored_runs(
                value, path + (key,)
            )

    elif isinstance(data, list):

        for i, value in enumerate(data):
            yield from find_stored_runs(
                value, path + (i,)
            )


