# Each method has the same structure

results = {}

for method, method_data in data.items():

    results[method] = {}

    for experiment_type, worlds in method_data.items():

        results[method][experiment_type] = {}

        for world, trials in worlds.items():

            results[method][experiment_type][world] = {}

            for trial, runs in trials.items():

                results[method][experiment_type][world][trial] = {}

                for run, run_data in runs.items():

                    sequence = run_data["sensor_sequence"]
                    success = float(run_data["success"])

                    # ----------------------------------------
                    # HITL
                    # ----------------------------------------

                    if method == "HITL":
                        # We manage the two matrices
                        matrix_llm = run_data["matrix_LLM"]
                        matrix_human = run_data["matrix_human"]

                        n_llm, _, _ = get_inspected_areas(matrix_llm)

                        # We consider the human final matrix
                        n_human, inspected_vector, weighted_vector = get_inspected_areas(matrix_human)

                        distance, distances_per_turn = normalized_hamming_distance(
                            matrix_llm,
                            matrix_human
                        )

                        matrix = matrix_human
                        n_inspected = n_human

                    # ----------------------------------------
                    # AUTO / ILP
                    # ----------------------------------------

                    else:

                        matrix = run_data["matrix"]

                        n_inspected, inspected_vector, weighted_vector = get_inspected_areas(matrix)
                        

                    # ----------------------------------------
                    # COMMON METRICS
                    # ----------------------------------------

                    n_total = run_data["n_total_areas"]

                    sequence_key = json.dumps(
                        sequence,
                        sort_keys=True
                    )

                    group_key = (
                        world,
                        sequence_key,
                        run_data["intruder_final_area"]
                    )

                    # We extract the minimum number of areas inspected among all methods for a given world, sensor sequence and final intruder area
                    A_min = minimum_areas.get(group_key)

                    # Computing the efficiency
                    efficiency = round(success * (1 - (n_inspected - A_min) / (n_total - A_min)),2)


                    # ----------------------------------------
                    # BUILD RUN RESULT
                    # ----------------------------------------

                    run_result = {
                        "sensor_sequence": sequence,
                        "inspection_binary_vector": inspected_vector,
                        "inspection_weighted_vector": weighted_vector
                    }

                    if method == "HITL":

                        run_result.update({
                            "n_inspected_areas_LLM": n_llm,
                            "n_inspected_areas_human": n_human,
                            "n_total_areas": n_total,
                            "min_inspected_areas": A_min,
                            "intruder_final_area": run_data["intruder_final_area"],
                            "success_rate": success,
                            "efficiency_human": round(efficiency, 2),
                            "normalized_hamming_distance": round(distance, 2),
                            "normalized_hamming_distance_per_turn": {
                                turn: round(value, 2)
                                for turn, value in distances_per_turn.items()
                            }
                        })

                    else:

                        run_result.update({
                            "n_inspected_areas": n_inspected,
                            "n_total_areas": n_total,
                            "min_inspected_areas": A_min,
                            "intruder_final_area": run_data["intruder_final_area"],
                            "success_rate": success,
                            "efficiency": round(efficiency, 2)
                        })

                    results[method][experiment_type][world][trial][run] = run_result


# ============================================================
# 5. SAVE RUN METRICS
