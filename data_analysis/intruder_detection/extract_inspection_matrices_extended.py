def process_run(run_data, world, camera_mappings):
    """
    Processes an experiment run to identify which areas of a world have been inspected during each LLM conversation turn.

    The function analyzes the conversation associated with a run and identifies sensor completion, user messages and robot function calls.

    The processing is divided into three main steps:

    1. Sensor completion:
       - Counts the messages containing "data_orchestrator".
       - Stops when the number of orchestrator messages reaches the number of expected sensors (sensor_sequence).
       - Considers only the messages occurring after sensor completion.

    2. Conversation filtering:
       - Checks whether real user messages are present after sensor completion.
       - If real user messages exist, they are used to identify new LLM turns.
       - If no real user messages exist, the conversation is limited to the last assistant response, if available.

    3. Inspection processing:
       - Analyzes function calls in the relevant conversation.
       - Identifies camera inspections and robot deployments.
       - Associates inspected areas with the corresponding conversation turn.

    Inspection levels:
       - 0.5: Area inspected through a camera feed.
       - 1: Area inspected through robot deployment.

       If an area is inspected multiple times during the same turn, the highest inspection level is retained.

    Example:

        run_data = {
            "sensor_sequence": [1, 2],
            "conversation": [
                {"data_orchestrator": "sensor_1 completed"},
                {"data_orchestrator": "sensor_2 completed"},
                {"function_call":'name - get_camera_feed arguments - {"cameras_names_list": ["camera_1"]}'},
                {"function_call":'name - send_robots_to_area arguments - {"robots_sequence": [{"area_to_reach": "F"}]}'},
                {"user": "Inspect area B with camera"},
                {"function_call": 'name - get_camera_feed arguments - {"cameras_names_list": ["camera_2"]}'}
            ]
        }

        world = "world_1"

        camera_mappings = {
            "world_1": {
                "camera_1": ["A"],
                "camera_2": ["B"]
            }
        }

        result = process_run(run_data, world, camera_mappings)

        Output:

        {
            1: {
                "A": 0.5,
                "F": 1
            },
            2: {
                "B": 0.5
            }
        }

    In this example:

        - The first two messages indicate sensor completion. They are excluded from the inspection analysis.
        - The first LLM turn contains two function calls: get_camera_feed inspects area A with level 0.5, while send_robots_to_area inspects area F with level 1.
        - The real user message starts a new LLM turn.

        - The second turn contains a camera inspection of area B, which receives inspection level 0.5.

    Args:
        run_data (dict):
            Dictionary containing the experiment data.
            It must include:
                - "conversation": List of conversation messages.
                - "sensor_sequence": List of expected sensors.

        world (str):
            Name of the world in which the experiment takes place.
            It is used to select the corresponding camera mappings.

        camera_mappings (dict):
            Dictionary associating each world with its camera mappings.
            Each camera is associated with one or more inspected areas.

            Example:
                {
                    "world_1": {
                        "camera_1": ["A", "B"],
                        "camera_2": "C"
                    }
                }

    Returns:
        dict:
            Dictionary containing the inspected areas grouped
            by LLM conversation turn.

            Each turn contains:
                - Area name as key.
                - Inspection level (0.5 or 1) as value.

            Returns an empty dictionary if sensor completion
            is not detected.
    """

    conversation = run_data["conversation"]
    sensor_sequence = run_data["sensor_sequence"]

    expected_sensors = len(sensor_sequence)

    # ------------------------------------------------
    # 1. Find sensor completion
    # ------------------------------------------------

    orchestrator_count = 0
    sensor_completion_index = None

    for i, message in enumerate(conversation):

        if not isinstance(message, dict):
            continue

        if "data_orchestrator" in message:
            orchestrator_count += 1

            if orchestrator_count >= expected_sensors:
                sensor_completion_index = i
                break

    if sensor_completion_index is None:
        print("WARNING: Sensor sequence not completed")
        return {}

    post_sensor_conversation = conversation[
        sensor_completion_index + 1:
    ]

    # ------------------------------------------------
    # 2. Identify whether there are real user messages
    # ------------------------------------------------

    has_real_user = any(is_real_user_message(message) for message in post_sensor_conversation)

    # If no real user message exists, consider the
    # conversation until the last assistant response.

    if not has_real_user:

        last_assistant_index = None

        for i, message in enumerate(post_sensor_conversation):

            if isinstance(message, dict) and "assistant" in message:
                last_assistant_index = i

        if last_assistant_index is not None:
            relevant_conversation = post_sensor_conversation[
                :last_assistant_index + 1
            ]
        else:
            relevant_conversation = post_sensor_conversation

    else:
        relevant_conversation = post_sensor_conversation

    # ------------------------------------------------
    # 3. Process inspections
    # ------------------------------------------------

    current_turn = 1
    inspections = {}

    inspections[current_turn] = {}

    camera_mapping = camera_mappings.get(world, {})

    for message in relevant_conversation:

        if not isinstance(message, dict):
            continue

        # --------------------------------------------
        # Real user message: new LLM turn
        # --------------------------------------------

        if is_real_user_message(message):

            if has_real_user:
                current_turn += 1
                inspections.setdefault(current_turn, {})

            continue

        # --------------------------------------------
        # Ignore assistant messages
        # --------------------------------------------

        # --------------------------------------------
        # Extract function calls
        # --------------------------------------------

        function_name, arguments = extract_function_data(message)

        if function_name is None:
            continue

        inspections.setdefault(current_turn, {})

        # --------------------------------------------
        # Camera inspection
        # --------------------------------------------

        if function_name == "get_camera_feed":

            cameras = arguments.get(
                "cameras_names_list", []
            )

            for camera in cameras:

                areas = camera_mapping.get(
                    camera.lower(), []
                )

                if isinstance(areas, str):
                    areas = [areas]

                for area in areas:

                    inspections[current_turn][area] = max(
                        inspections[current_turn].get(area, 0),
                        0.5
                    )

        # --------------------------------------------
        # Robot deployment
        # --------------------------------------------

        elif function_name == "send_robots_to_area":

            robots = arguments.get(
                "robots_sequence", []
            )

            for robot in robots:

                area = robot.get("area_to_reach")

                if area is None:
                    continue

                inspections[current_turn][area] = max(
                    inspections[current_turn].get(area, 0),
                    1
                )

    return inspections



