# 4. CALCULATE METRICS FOR EACH RUN
# ============================================================

# the dictionary 'data' will be structured as:
# "HITL": {
#     "deterministic": {
#         "world_1": {
#             "trial_1": {
#                 "run_1": {
#     "uncertain": {
