# 1. BUILD INSPECTION VECTORS
# ============================================================

def get_inspected_areas(matrix):
    """
    Processes an inspection matrix to determine the number of inspected areas
    and generate binary and weighted inspection vectors.

    Input:
        matrix (dict): Inspection matrix structured by turns, where each turn
            contains a dictionary mapping area identifiers to inspection
            values. Values can be scalars or lists.

                        "matrix": {
                            "1": {
                                "A": 0.0,
                                "B": 1.0,
                                "C": 10.0,
                                "D": 0.0,
                                "E": 0.0,
                                "F": 0.0,
                                "G": 0.0,
                                "H": 0.0,
                                "I": 0.0,
                                "L": 0.0
                            },
                            "2": {
                                "A": 0.0,
                                "B": 0.0,
                                "C": 10.0,
                                "D": 0.0,
                                "E": 0.0,
                                "F": 0.0,
                                "G": 0.0,
                                "H": 0.0,
                                "I": 0.0,
                                "L": 0.0
                            }

    Processing:
        - Binary vector: assigns 1 to an area if it has been inspected at
          least once, and 0 otherwise.
        - Weighted vector: accumulates the inspection values across all turns,
          accounting for multiple inspections of the same area.
        - Counts the total number of distinct inspected areas.

    Returns:
        tuple:
            - n_inspected (int): Total number of distinct inspected areas.
            - binary_inspected_areas (dict): Binary inspection vector,
              structured as {area: 0 or 1}.
            - weighted_inspected_areas (dict): Weighted inspection vector,
              structured as {area: accumulated inspection value}.
    """

    # Vectors initialization
    binary_inspected_areas = {
        area: 0
        for turn_data in matrix.values()
        for area in turn_data
    }

    weighted_inspected_areas = {
        area: 0
        for turn_data in matrix.values()
        for area in turn_data
    }

    # Loop on turns
    for turn_data in matrix.values():

        for area, value in turn_data.items():

            if isinstance(value, list):
                values = value
            else:
                values = [value]

            for v in values:

                if v != 0:
                    binary_inspected_areas[area] = 1

                weighted_inspected_areas[area] += v

    n_inspected = sum(binary_inspected_areas.values())

    return n_inspected, binary_inspected_areas, weighted_inspected_areas

