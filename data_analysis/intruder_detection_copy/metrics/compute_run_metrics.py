# 9. CALCULATE JACCARD AND COSINE SIMILARITIES
# ============================================================

jaccard_results = {}
cosine_results = {}

for (
    experiment_type,
    world,
    trial,
    sequence
), method_data in sequence_groups.items():

    jaccard_results.setdefault(experiment_type, {})
    jaccard_results[experiment_type].setdefault(world, {})
    jaccard_results[experiment_type][world].setdefault(trial, {})

    cosine_results.setdefault(experiment_type, {})
    cosine_results[experiment_type].setdefault(world, {})
    cosine_results[experiment_type][world].setdefault(trial, {})

    jaccard_pairs = {}
    cosine_binary_pairs = {}
    cosine_weighted_pairs = {}

    available_methods = [
        method
        for method in results.keys()
        if method in method_data
    ]

    for method_a, method_b in combinations(available_methods, 2):

        pair_name = f"{method_a}-{method_b}"

        vector_a = method_data[method_a][0]
        vector_b = method_data[method_b][0]

        # Jaccard: binary vectors

        jac_similarity = jaccard_similarity(
            vector_a["binary"],
            vector_b["binary"]
        )

        jaccard_pairs[pair_name] = round(jac_similarity, 4)

        # Cosine: binary vectors

        bin_cos_similarity = cosine_similarity(
            vector_a["binary"],
            vector_b["binary"]
        )

        cosine_binary_pairs[pair_name] = round(bin_cos_similarity, 4)

        # Cosine: weighted vectors

        weigh_cos_similarity = cosine_similarity(
            vector_a["weighted"],
            vector_b["weighted"]
        )

        cosine_weighted_pairs[pair_name] = round(weigh_cos_similarity, 4)


    jaccard_results[experiment_type][world][trial][sequence] = (jaccard_pairs)

    cosine_results[experiment_type][world][trial][sequence] = {
        "binary": cosine_binary_pairs,
        "weighted": cosine_weighted_pairs
    }


