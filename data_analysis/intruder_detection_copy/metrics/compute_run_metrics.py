# 6. JACCARD SIMILARITY
# ============================================================

def jaccard_similarity(vector_a, vector_b):

    # Extraction of the areas list
    areas = vector_a.keys()

    # Computing intersection among inspected areas
    intersection = sum(
        vector_a.get(area, 0) == 1 and vector_b.get(area, 0) == 1
        for area in areas
    )

    # Computing the union of inspected areas
    union = sum(
        vector_a.get(area, 0) == 1 or vector_b.get(area, 0) == 1
        for area in areas
    )

    return intersection / union if union > 0 else 1.0


# ============================================================
# 7. COSINE SIMILARITY
# ============================================================

def cosine_similarity(vector_a, vector_b):

    # Transforming inspection vectors in arrays
    values_a = np.array(
        list(vector_a.values()),
        dtype=float
    )

    values_b = np.array(
        list(vector_b.values()),
        dtype=float
    )

    # Computing norms
    norm_a = np.linalg.norm(values_a)
    norm_b = np.linalg.norm(values_b)

    if norm_a == 0 and norm_b == 0:
        return 1.0

    if norm_a == 0 or norm_b == 0:
        return 0.0

    return float(np.dot(values_a, values_b) / (norm_a * norm_b))


