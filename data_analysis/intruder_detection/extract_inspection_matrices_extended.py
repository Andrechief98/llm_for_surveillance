def find_runs(data, path=()):
    """
    Find experiment runs recursively inside nested JSON data.

    A run is identified by the presence of the key "sensor_sequence".

    Example:
        data = {
            "experiment_1": {
                "runs": [
                    {"sensor_sequence": [10, 20, 30]},
                    {"sensor_sequence": [40, 50, 60]}
                ]
            }
        }

        for path, run in find_runs(data):
            print(path, run)

        Output:
            ('experiment_1', 'runs', 0) {'sensor_sequence': [10, 20, 30]}
            ('experiment_1', 'runs', 1) {'sensor_sequence': [40, 50, 60]}

    Args:
        data: Nested dictionary or list containing experiment data.
        path: Tuple tracking the current position in the JSON structure.

    Yields:
        A tuple containing:
            - path: Position of the run in the original JSON.
            - data: Dictionary containing the sensor_sequence.
    """

    if isinstance(data, dict):

        if ("sensor_sequence" in data and ("conversation" in data or "actions" in data)):
            yield path, data
            return

        for key, value in data.items():
            yield from find_runs(value, path + (key,))

    elif isinstance(data, list):

        for i, value in enumerate(data):
            yield from find_runs(value, path + (i,))



def is_real_user_message(message):
    """
    Distinguishes actual user messages from robot notifications.

    The function checks whether a message contains valid user text
    or whether it is an automatic notification generated by a robot.

    A message is considered valid if:
        - It is a dictionary.
        - It contains the key "user".
        - The value associated with "user" is a string.
        - The text does not start with a robot identifier (e.g., turtlebot3_2:) typically related to the robot notification.

    Robot notifications are identified using a regular expression that matches robot names such as:
        turtlebot3_2:
        turtlebot1_1:
        turtlebot10_3:

    Example:
        # Real user message
        message = {
            "user": "Hello, can you help me?"
        }

        is_real_user_message(message)
        # Output: True

        # Robot notification
        message = {
            "user": "turtlebot3_2: Goal reached. Area F: Intruder identified"
        }

        is_real_user_message(message)
        # Output: False

        # Missing user key
        message = {
            "robot": "turtlebot3_2"
        }

        is_real_user_message(message)
        # Output: False

        # Invalid message type
        message = "Hello!"

        is_real_user_message(message)
        # Output: False

    Args:
        message (dict): Dictionary containing the message to analyze. The expected key is "user".

    Returns:
        bool:
            True if the message contains valid user text.
            False if the message is invalid or generated by a robot.
    """

    if not isinstance(message, dict):
        return False

    if "user" not in message:
        return False

    content = message["user"]

    if not isinstance(content, str):
        return False

    # Robot notification, e.g.:
    # turtlebot3_2: Goal reached. Area F: Intruder identified

    if re.match(
        r"^\s*turtlebot\d+_\d+\s*:",
        content,
        re.IGNORECASE
    ):
        return False

    return True


def extract_function_data(message):
    """
    Extracts the function name and its arguments from the "function_call" key of a message.

    The function searches for a specific structure inside the "function_call" string:
        name - FUNCTION_NAME arguments - {JSON_ARGUMENTS}

    It extracts two elements:
        - function_name: Name of the function being called.
        - arguments: Dictionary containing the function arguments.

    The extracted arguments are converted from a JSON string
    into a Python dictionary using json.loads().

    The function returns (None, None) if:
        - message is not a dictionary.
        - The "function_call" field is missing.
        - The "function_call" field is not a string.
        - The expected structure cannot be found.
        - The arguments contain invalid JSON.

    Example:
        # Valid function call
        message =  {
                  "function_call": "name - compute_robot_area_distance \n\targuments - {\"areas_to_inspect\":[\"F\"]}",
                  "tool_params_generation_time": 0.14
                }

        extract_function_data(message)

        # Output:
            'compute_robot_area_distance'
            {'areas_to_inspect': ["F"]}

    Args:
        message (dict): Dictionary containing the "function_call"
                        field with the function name and arguments.

    Returns:
        tuple:
            - function_name (str): Name of the called function.
            - arguments (dict): Parsed function arguments.

            Returns (None, None) if extraction or JSON parsing fails.
    """

    if not isinstance(message, dict):
        return None, None

    function_call = message.get("function_call")

    if not isinstance(function_call, str):
        return None, None

    match = re.search(
        r"name\s*-\s*(.*?)\s*arguments\s*-\s*(\{.*\})",
        function_call,
        re.DOTALL
    )

    if not match:
        return None, None

    function_name = match.group(1).strip()
    arguments_string = match.group(2).strip()

    try:
        arguments = json.loads(arguments_string)
    except json.JSONDecodeError:
        return None, None

    return function_name, arguments


