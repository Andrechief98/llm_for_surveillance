# 2. NORMALIZED HAMMING DISTANCE
# ============================================================

def normalized_hamming_distance(matrix_llm, matrix_human):
    """
    Computes the normalized Hamming distance between two inspection matrices,
    representing LLM-generated and human-generated inspections.

    Input:
        matrix_llm (dict): Inspection matrix generated by the LLM, structured
            by turns and areas, with inspection values.
        matrix_human (dict): Inspection matrix generated by the human,
            structured in the same way.

    Processing:
        - Compares the LLM and human binary inspection vector for every turn.
        - Computes the Hamming distance (for each turn) as the number of areas with different
          inspection statuses, divided by the union of inspected areas (total number of areas
          proposed by both the LLM and the human).
        - Assigns a distance of 0.0 when neither approach inspects any area
          during a given turn.
        - Calculates the mean across all turns.

    Returns:
        tuple:
            - mean_normalized_distance (float): Mean normalized Hamming distance across
              all turns.
            - normalized_distances_per_turn (dict): Dictionary mapping each turn
              identifier to its corresponding normalized Hamming distance,
              structured as {turn: distance}.
    """

    # Extraction number of turns (the same for both matrix_llm and matrix_human)
    turns = matrix_llm.keys()
    
    normalized_distances_per_turn = {}

    for turn in sorted(turns, key=lambda x: int(x)):

        # Extracting matrices of the considered turn
        llm = matrix_llm.get(turn, {})
        human = matrix_human.get(turn, {})

        # Extracting list of all areas (the same for both matrices)
        areas = llm.keys()

        hamming = 0
        active_union = 0

        for area in areas:

            # Check if the considered area is active in both matrices
            llm_active = llm.get(area, 0) != 0
            human_active = human.get(area, 0) != 0

            if llm_active != human_active:
                # Increasing the distance
                hamming += 1

            if llm_active or human_active:
                # Increasing the union
                active_union += 1

        normalized_distance = (
            hamming / active_union
            if active_union > 0 else 0.0
        )

        normalized_distances_per_turn[turn] = normalized_distance

    mean_normalized_distance = (
        float(np.mean(list(normalized_distances_per_turn.values())))
        if normalized_distances_per_turn else 0.0
    )

    return mean_normalized_distance, normalized_distances_per_turn


